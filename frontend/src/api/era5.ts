import {apiClient} from './client'
export const era5Api={
  status:()=>apiClient.get('/era5/status').then(r=>r.data.data),
  sources:()=>apiClient.get('/era5/sources').then(r=>r.data.data),
  checkSource:(id:string)=>apiClient.post(`/era5/sources/${id}/check`,null,{timeout:60000}).then(r=>r.data.data),
  benchmarkSource:(id:string)=>apiClient.post(`/era5/sources/${id}/benchmark`,null,{timeout:240000}).then(r=>r.data.data),
  setDefaultSource:(source_id:string)=>apiClient.put('/era5/sources/default',{source_id}).then(r=>r.data.data),
  publicSample:()=>apiClient.post('/era5/public-sample',null,{timeout:180000}).then(r=>r.data.data),
  batchPreview:(per_split=2)=>apiClient.get('/era5/public-batches/preview',{params:{per_split},timeout:30000}).then(r=>r.data.data),
  createBatch:(per_split=2)=>apiClient.post('/era5/public-batches',null,{params:{per_split}}).then(r=>r.data.data),
  scalePreview:(max_samples=12)=>apiClient.get('/era5/scale-batches/preview',{params:{max_samples},timeout:30000}).then(r=>r.data.data),
  createScaleBatch:(max_samples=12)=>apiClient.post('/era5/scale-batches',null,{params:{max_samples}}).then(r=>r.data.data),
  batches:()=>apiClient.get('/era5/public-batches').then(r=>r.data.data),
  cancelBatch:(id:string)=>apiClient.post(`/era5/public-batches/${id}/cancel`).then(r=>r.data.data),
  resumeBatch:(id:string)=>apiClient.post(`/era5/public-batches/${id}/resume`).then(r=>r.data.data),
  test:()=>apiClient.post('/era5/connection-test').then(r=>r.data.data),
  plans:()=>apiClient.get('/era5/plans',{timeout:30000}).then(r=>r.data.data),
  jobs:()=>apiClient.get('/era5/jobs').then(r=>r.data.data),
  createJob:(payload:any)=>apiClient.post('/era5/jobs',payload).then(r=>r.data.data),
  cancelJob:(id:string)=>apiClient.post(`/era5/jobs/${id}/cancel`).then(r=>r.data.data),
  retryJob:(id:string)=>apiClient.post(`/era5/jobs/${id}/retry`).then(r=>r.data.data),
  files:()=>apiClient.get('/era5/files').then(r=>r.data.data),
  statistics:()=>apiClient.get('/era5/samples/statistics',{timeout:30000}).then(r=>r.data.data),
  samples:(params?:object)=>apiClient.get('/era5/samples',{params,timeout:30000}).then(r=>r.data.data),
  sample:(id:string)=>apiClient.get(`/era5/samples/${id}`,{timeout:30000}).then(r=>r.data.data),
  audit:()=>apiClient.get('/era5/samples/audit',{timeout:30000}).then(r=>r.data.data),
  freeze:()=>apiClient.post('/era5/samples/freeze').then(r=>r.data.data),
  build:(limit?:number)=>apiClient.post('/era5/samples/build',null,{params:{limit}}).then(r=>r.data.data),
  importFile:(file:File)=>{const form=new FormData();form.append('file',file);return apiClient.post('/era5/import',form,{timeout:120000}).then(r=>r.data.data)},
}
